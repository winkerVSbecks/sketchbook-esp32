// ============================================================================
// palettes.h — the sketchbook-ssam palette sets, as 0xRRGGBB tables
// ============================================================================
// Ported from sketchbook-ssam/src/colors/*.ts. The auto-albers entries are
// authored in oklab/oklch and several sit well outside sRGB (chroma up to
// 0.40), so they were converted through culori's clampChroma — the same gamut
// mapping the browser applies — rather than by naive clipping, which would
// flatten distinct ramp steps into one colour.
//
// Regenerate with the script in the repo's docs if the JS palettes change; the
// values below are a snapshot, not a live import.
//
// Rows are padded to a fixed width; always read the length from the matching
// _LENS table rather than the array bound.
// ============================================================================
