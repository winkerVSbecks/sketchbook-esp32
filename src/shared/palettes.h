// ---------------------------------------------------------------------------
// Selection
// ---------------------------------------------------------------------------
static inline Palette clrsAt(int i)       { return Palette{ CLRS[i],        CLRS_LENS[i] }; }
static inline Palette autoAlbersAt(int i) { return Palette{ AUTO_ALBERS[i], AUTO_ALBERS_LENS[i] }; }
static inline Palette mindfulAt(int i)    { return Palette{ MINDFUL[i],     MINDFUL_LENS[i] }; }

// colors/index.ts randomPalette(): a flat pick across clrs + auto-albers +
// mindful, so the larger sets are proportionally more likely.
static inline Palette randomPalette() {
  int i = rngIndex(CLRS_COUNT + AUTO_ALBERS_COUNT + MINDFUL_COUNT);
  if (i < CLRS_COUNT) return clrsAt(i);
  i -= CLRS_COUNT;
  if (i < AUTO_ALBERS_COUNT) return autoAlbersAt(i);
  return mindfulAt(i - AUTO_ALBERS_COUNT);
}

// The trochoidal-wave sketch picks from mindful + auto-albers only.
static inline Palette randomMindfulOrAlbers() {
  int i = rngIndex(MINDFUL_COUNT + AUTO_ALBERS_COUNT);
  return i < MINDFUL_COUNT ? mindfulAt(i) : autoAlbersAt(i - MINDFUL_COUNT);
}
